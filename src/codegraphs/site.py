"""Navigation for the published viewers (GitHub Pages).

build_index(output_dir) scans output/<project>-<version>/manifest.json and writes
  output/versions.js   window.CODEGRAPHS_INDEX = {project: [{version, n_files, ...}, ...]}
                       loaded by every viewer.html (version dropdown); a <script> include, so it
                       also works when the pages are opened from disk (file://)
  index.html           landing page next to output/ (the repository root = GitHub Pages root)
Regenerating the index updates the navigation of all viewers without rebuilding them.
"""
import html
import json
import re
from pathlib import Path

SUMMARY_KEYS = ("n_files", "n_functions", "n_files_with_parse_errors",
                "n_functions_with_parse_errors", "n_bodiless_functions_skipped", "language", "tag")


def version_key(v: str):
    """Natural order: 1.2 < 1.10 < 2.0; 5.0.0 < 5.8.0."""
    return tuple(int(p) if p.isdigit() else p for p in re.split(r"[.\-]", v))


def collect(output_dir: Path) -> dict:
    index = {}
    for m in sorted(Path(output_dir).glob("*/manifest.json")):
        if not (m.parent / "viewer.html").exists():
            continue
        man = json.loads(m.read_text(encoding="utf8"))
        project, version = man.get("project"), man.get("version")
        if not project or not version:
            continue
        entry = {"version": version, **{k: man[k] for k in SUMMARY_KEYS if k in man}}
        index.setdefault(project, []).append(entry)
    for entries in index.values():
        entries.sort(key=lambda e: version_key(e["version"]))
    return dict(sorted(index.items()))


def _landing_page(index: dict, output_rel: str) -> str:
    sections = []
    for project, entries in index.items():
        rows = "\n".join(
            "<tr><td><a href=\"{href}\">{v}</a></td><td>{files:,}</td><td>{funcs:,}</td>"
            "<td>{perr}</td></tr>".format(
                href=html.escape(f"{output_rel}/{project}-{e['version']}/viewer.html"),
                v=html.escape(e["version"]), files=e.get("n_files", 0),
                funcs=e.get("n_functions", 0), perr=e.get("n_functions_with_parse_errors", 0))
            for e in entries)
        lang = html.escape(entries[0].get("language", "")) if entries else ""
        sections.append(
            f"<h2>{html.escape(project)} <span class=\"lang\">{lang}</span></h2>\n"
            "<table><tr><th>Version</th><th>Files</th><th>Functions</th>"
            f"<th>Parse errors</th></tr>\n{rows}\n</table>")
    body = "\n".join(sections) or "<p>No viewers built yet.</p>"
    return f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>Control / data flow graphs</title>
<style>
 body{{font-family:Segoe UI,Arial,sans-serif;font-size:14px;margin:24px 40px;color:#222}}
 table{{border-collapse:collapse;margin-bottom:18px}}
 th,td{{border-bottom:1px solid #ddd;padding:4px 14px;text-align:right}}
 th:first-child,td:first-child{{text-align:left}}
 .lang{{font-size:13px;color:#777;font-weight:normal}}
</style></head><body>
<h1>Control flow and data flow graphs</h1>
<p>Per-function CFG/DFG viewers, one page per project version. Generated by
<code>python -m codegraphs</code>; see the repository README.</p>
{body}
</body></html>
"""


def build_index(output_dir: Path, site_root: Path = None) -> dict:
    output_dir = Path(output_dir)
    site_root = Path(site_root) if site_root is not None else output_dir.resolve().parent
    index = collect(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_dir / "versions.js", "w", encoding="utf8", newline="\n") as fh:
        fh.write("window.CODEGRAPHS_INDEX = " + json.dumps(index, indent=1) + ";\n")
    output_rel = output_dir.resolve().relative_to(site_root.resolve()).as_posix()
    with open(site_root / "index.html", "w", encoding="utf8", newline="\n") as fh:
        fh.write(_landing_page(index, output_rel))
    n = sum(len(v) for v in index.values())
    print(f"[done] {site_root / 'index.html'} + {output_dir / 'versions.js'} "
          f"({len(index)} projects, {n} versions)")
    return index
